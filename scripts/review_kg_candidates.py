"""
Tier 2 PR C-1 — local review UI for knowledge-graph v2 verdicts.

Walks the human reviewer through every `contraindicated` verdict
generated by `expand_knowledge_graph.py`, plus a deterministic 10% sample
of `safe` verdicts. Per the Tier 2 plan this review step is a HARD STOP
before the v2 file can be promoted to the iOS bundle.

Decisions saved live (each click → POST → file write) to
`scripts/output/kg_review_decisions.json`. Resume-friendly: re-running the
tool picks up where the last session left off.

Verdicts the reviewer can apply:
  - APPROVE  → keep as-is
  - REJECT   → drop this verdict from the merged v2 (treat as unverified)
  - FLIP     → flip safe ↔ contraindicated (use only when the AI is
               clearly wrong about direction)
  - EDIT     → free-text override of the reason (rarely needed)

When done, run `scripts/merge_kg_review.py` (separate small script,
intentionally NOT created in PR C-1 because we want explicit human
review of the merge step too) to produce the final v2 graph.

Usage:
  python scripts/review_kg_candidates.py
  python scripts/review_kg_candidates.py --port 5302
  python scripts/review_kg_candidates.py --safe-sample-percent 20
"""
from __future__ import annotations

import argparse
import json
import random
from http.server import HTTPServer, SimpleHTTPRequestHandler
from pathlib import Path
from urllib.parse import urlparse

SCRIPT_DIR = Path(__file__).resolve().parent
OUTPUT_DIR = SCRIPT_DIR / "output"
DRAFT_INPUT = OUTPUT_DIR / "knowledge_graph_v2_draft.json"
DECISIONS_FILE = OUTPUT_DIR / "kg_review_decisions.json"

DEFAULT_SAFE_SAMPLE_PERCENT = 10
RANDOM_SEED = 42  # deterministic sample so the same verdicts get reviewed across re-runs


# ---------------------------------------------------------------------------
# Decision storage
# ---------------------------------------------------------------------------

def load_decisions() -> dict:
    if DECISIONS_FILE.exists():
        try:
            return json.loads(DECISIONS_FILE.read_text())
        except json.JSONDecodeError:
            return {}
    return {}


def save_decisions(decisions: dict) -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    DECISIONS_FILE.write_text(json.dumps(decisions, indent=2, sort_keys=True))


def decision_key(verdict_row: dict) -> str:
    return f"{verdict_row['condition_id']}|{verdict_row['exercise_id']}"


# ---------------------------------------------------------------------------
# Build the review queue: all contraindicated + 10% of safe
# ---------------------------------------------------------------------------

def build_entries(safe_sample_percent: int) -> list[dict]:
    if not DRAFT_INPUT.exists():
        raise SystemExit(
            f"ERROR: {DRAFT_INPUT} not found.\n"
            "Run `scripts/expand_knowledge_graph.py` first to generate the draft."
        )
    draft = json.loads(DRAFT_INPUT.read_text())
    verdicts = draft.get("verdicts", [])

    contraindicated = [v for v in verdicts if v.get("verdict") == "contraindicated"]
    safe = [v for v in verdicts if v.get("verdict") == "safe"]
    unclear = [v for v in verdicts if v.get("verdict") == "unclear"]

    # Deterministic sample of safes
    rng = random.Random(RANDOM_SEED)
    sample_n = max(0, len(safe) * safe_sample_percent // 100)
    safe_sample = rng.sample(safe, sample_n) if sample_n < len(safe) else safe[:]

    # Also surface ALL "unclear" verdicts — these are the ones the AI itself
    # punted on, so a human should make the call.
    queue = []
    for row in contraindicated:
        queue.append({**row, "review_bucket": "contraindicated"})
    for row in unclear:
        queue.append({**row, "review_bucket": "unclear"})
    for row in safe_sample:
        queue.append({**row, "review_bucket": "safe-sample"})

    decisions = load_decisions()
    for entry in queue:
        key = decision_key(entry)
        prior = decisions.get(key)
        entry["current_decision"] = prior.get("decision", "pending") if prior else "pending"
        entry["edited_reason"] = prior.get("edited_reason") if prior else None

    print(
        f"Review queue: {len(contraindicated)} contraindicated + "
        f"{len(unclear)} unclear + {len(safe_sample)}/{len(safe)} sampled safes "
        f"= {len(queue)} entries"
    )
    return queue


