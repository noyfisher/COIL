# ---------------------------------------------------------------------------
# HTTP handler
# ---------------------------------------------------------------------------

def make_handler(safe_sample_percent: int):
    class Handler(SimpleHTTPRequestHandler):
        def log_message(self, *a, **kw):
            pass

        def do_GET(self):
            url = urlparse(self.path)
            if url.path == "/":
                entries = build_entries(safe_sample_percent)
                body = HTML.format(entries_json=json.dumps(entries)).encode()
                self.send_response(200)
                self.send_header("content-type", "text/html; charset=utf-8")
                self.send_header("content-length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)
            elif url.path == "/export":
                data = (DECISIONS_FILE.read_bytes() if DECISIONS_FILE.exists() else b"{}\n")
                self.send_response(200)
                self.send_header("content-type", "application/json")
                self.send_header("content-disposition",
                                 'attachment; filename="kg_review_decisions.json"')
                self.send_header("content-length", str(len(data)))
                self.end_headers()
                self.wfile.write(data)
            else:
                self.send_error(404)

        def do_POST(self):
            if self.path != "/decide":
                self.send_error(404)
                return
            length = int(self.headers.get("content-length", "0"))
            payload = json.loads(self.rfile.read(length))
            decisions = load_decisions()
            decisions[payload["key"]] = {
                "decision": payload["decision"],
                "edited_reason": payload.get("edited_reason"),
            }
            save_decisions(decisions)
            self.send_response(204)
            self.end_headers()

    return Handler


def main() -> int:
    parser = argparse.ArgumentParser(description="Review KG v2 verdicts in a localhost UI")
    parser.add_argument("--port", type=int, default=5302)
    parser.add_argument("--safe-sample-percent", type=int, default=DEFAULT_SAFE_SAMPLE_PERCENT,
                        help=f"%% of 'safe' verdicts to sample for review (default {DEFAULT_SAFE_SAMPLE_PERCENT})")
    args = parser.parse_args()

    if not DRAFT_INPUT.exists():
        print(f"ERROR: {DRAFT_INPUT.relative_to(SCRIPT_DIR.parent)} not found.")
        print("Run `scripts/expand_knowledge_graph.py` first.")
        return 1

    print(f"\nKG review server: http://localhost:{args.port}/")
    print(f"Decisions save live to {DECISIONS_FILE.relative_to(SCRIPT_DIR.parent)}")
    print("Use the 'Download decisions' button when finished, then run the merge step.\n")
    HTTPServer(("127.0.0.1", args.port), make_handler(args.safe_sample_percent)).serve_forever()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
